bool _inside(double x, double y, List<double> p) {
  var c = false;
  for (var i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    final xi = p[i], yi = p[i + 1], xj = p[j], yj = p[j + 1];
    if ((yi > y) != (yj > y) && x < (xj - xi) * (y - yi) / (yj - yi) + xi) {
      c = !c;
    }
  }
  return c;
}

bool _inAny(double x, double y, List<List<double>> l) {
  for (final p in l) {
    if (_inside(x, y, p)) return true;
  }
  return false;
}

int _biome(double lat, double lon) {
  if (lat < -66) return 0;
  if (lat > 60 && lon > -60 && lon < -15) return 0;
  if (lat > 72) return 0;
  if (lat.abs() > 58) return 1;
  if ((lat > 14 && lat < 33 && lon > -17 && lon < 58) ||
      (lat < -17 && lat > -33 && lon > 118 && lon < 145) ||
      (lat > 36 && lat < 46 && lon > 88 && lon < 112) ||
      (lat < -18 && lat > -28 && lon > 12 && lon < 24)) {
    return 2;
  }
  if (lat.abs() < 12 &&
      ((lon > -76 && lon < -48) ||
          (lon > 8 && lon < 30) ||
          (lon > 95 && lon < 150))) {
    return 3;
  }
  return 4;
}

List<(double, double, int)> buildLand() {
  final out = <(double, double, int)>[];
  for (var lat = -84.0; lat <= 84; lat += 1.5) {
    final step = 1.5 / cos(lat * pi / 180);
    for (var lon = -180.0; lon < 180; lon += step) {
      if (_inAny(lon, lat, kLand) && !_inAny(lon, lat, kWater)) {
        out.add((lat, lon, _biome(lat, lon)));
      }
    }
  }
  return out;
}

